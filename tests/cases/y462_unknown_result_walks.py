def walk(obj, out, depth):
    r = obj.render(depth)
    out.append(r)
    for child in obj.children:
        walk(child, out, depth + 1)
    for key, value in obj.items():
        out.append(value.describe(key))
        walk(value, out, depth + 1)
    return out


